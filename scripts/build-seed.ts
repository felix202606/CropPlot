import { writeFileSync } from "node:fs";
import { plants } from "../lib/plants.ts";

const values = plants
  .map((plant) => {
    const data = {
      name: plant.name,
      emoji: plant.emoji,
      family: plant.family,
      sun: plant.sun,
      water: plant.water,
      spacing: plant.spacing,
      daysToHarvest: plant.daysToHarvest,
      intro: plant.intro,
      good: plant.good,
      avoid: plant.avoid,
    };
    return `  ('${plant.slug}', $json$${JSON.stringify(data)}$json$::jsonb)`;
  })
  .join(",\n");

const sql = `-- Generated by scripts/build-seed.ts from lib/plants.ts. Do not edit by hand.
insert into public.companion_matrix (slug, data) values
${values}
on conflict (slug) do update
set data = excluded.data, updated_at = now();
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql (${plants.length} plants)`);
